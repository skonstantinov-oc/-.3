// Видаляє з потоку залишок поточного рядка та скидає стан помилки.
void clearLine() {
    cin.clear();
    cin.ignore(numeric_limits<streamsize>::max(), '\n');
}

// Зчитує одне дійсне число. Повертає true, якщо введене слово
// повністю є коректним скінченним числом (наприклад, "abc" або "1.5x" -> false).
bool readDouble(double& value) {
    string token;
    if (!(cin >> token)) return false;           // кінець введення або збій потоку
    char* end = nullptr;
    value = strtod(token.c_str(), &end);         // перетворення рядка в число
    return *end == '\0' && isfinite(value);      // увесь рядок використано, число не inf/nan
}

// Зчитує одне ціле число (для пункту меню). "1.5" або "abc" -> false.
bool readInt(int& value) {
    string token;
    if (!(cin >> token)) return false;
    char* end = nullptr;
    long v = strtol(token.c_str(), &end, 10);
    if (*end != '\0' || v < -1000000 || v > 1000000) return false;
    value = static_cast<int>(v);
    return true;
}

// ---------------------------------------------------------------
// Завдання 1а. If16
// Дано три дійсні змінні A, B, C. Якщо їх значення впорядковані
// за зростанням (A < B < C), то подвоїти їх; в іншому випадку
// замінити значення кожної змінної на протилежне.
// Вивести нові значення A, B, C.
// ---------------------------------------------------------------
void taskIf16() {
    double A, B, C;
    cout << "\n************* If16 *************\n";
    cout << "Введіть три дійсні числа A, B, C через пробіл: ";

    // перевірка коректності введення
    if (!readDouble(A) || !readDouble(B) || !readDouble(C)) {
        cout << "Помилка: потрібно ввести три дійсні числа!\n";
        clearLine();
        return;
    }
    clearLine();   // прибираємо зайві символи в кінці рядка

    if (A < B && B < C) {            // умова впорядкованості за зростанням
        A *= 2;
        B *= 2;
        C *= 2;
        cout << "Числа впорядковані за зростанням -> подвоєно.\n";
    } else {
        A = 0.0 - A;                 // «0 - x» замість «-x», щоб не отримати значення «-0»
        B = 0.0 - B;
        C = 0.0 - C;
        cout << "Числа не впорядковані за зростанням -> змінено знаки.\n";
    }
    cout << "A = " << A << ", B = " << B << ", C = " << C << endl;
}

