// Завдання 1б. If12
// Дано три числа. Знайти найменше з них.
// ---------------------------------------------------------------
void taskIf12() {
    double A, B, C;
    cout << "\n************* If12 *************\n";
    cout << "Введіть три числа через пробіл: ";

    if (!readDouble(A) || !readDouble(B) || !readDouble(C)) {
        cout << "Помилка: потрібно ввести три числа!\n";
        clearLine();
        return;
    }
    clearLine();

    double minimum = A;              // вважаємо найменшим перше число
    if (B < minimum) minimum = B;    // порівнюємо з другим
    if (C < minimum) minimum = C;    // порівнюємо з третім

    cout << "Найменше число: " << minimum << endl;
}

// ---------------------------------------------------------------
// Завдання 2. Фігура 32 (помаранчева область)
//
// r - радіус кола. Позначимо s = r*sqrt(2), c = r/sqrt(2).
// Коло має центр (c; c) і проходить через точки (0;0), (s;0), (0;s).
// Помаранчева область складається з двох частин:
//   1) лівий трикутник з вершинами (-s;0), (0;s), (0;0) БЕЗ частини кола,
//      що лежить у ньому (ця частина кола має інший колір);
//   2) трикутник усередині кола з вершинами (0;0), (s;0), (c;c).
// Точки на межі області вважаємо такими, що належать їй.
// ---------------------------------------------------------------
void taskFigure32() {
    double r, x, y;
    cout << "\n************* Фігура 32 *************\n";
    cout << "Введіть радіус кола r (r > 0): ";

    if (!readDouble(r)) {
        cout << "Помилка: радіус має бути числом!\n";
        clearLine();
        return;
    }
    if (r <= 0) {
        cout << "Помилка: радіус має бути додатним!\n";
        clearLine();
        return;
    }
    cout << "Введіть координати точки x та y через пробіл: ";
    if (!readDouble(x) || !readDouble(y)) {
        cout << "Помилка: координати мають бути числами!\n";
        clearLine();
        return;
    }
    clearLine();

    const double s   = r * sqrt(2.0);     // півдіагональ ромба
    const double c   = r / sqrt(2.0);     // координати центра кола (c; c)
    const double eps = 1e-9 * r;          // похибка для порівнянь на межі
    const double eps2 = 1e-9 * r * r;     // те саме для квадратів відстаней

    // квадрат відстані від точки до центра кола
    double d2 = (x - c) * (x - c) + (y - c) * (y - c);

    // точка лежить зовні кола або на колі
    bool outsideCircle = d2 >= r * r - eps2;

    // частина 1: лівий трикутник (x <= 0, y >= 0, під прямою y = x + s) без кола
    bool inLeftTriangle = x <= eps && y >= -eps && y <= x + s + eps;
    bool part1 = inLeftTriangle && outsideCircle;

    // частина 2: трикутник (0;0), (s;0), (c;c):
    // вище осі OX, нижче прямої y = x та лівіше прямої x + y = s
    bool part2 = y >= -eps && y <= x + eps && x + y <= s + eps;

    if (part1 || part2)
        cout << "Точка (" << x << "; " << y << ") належить помаранчевій області.\n";
    else
        cout << "Точка (" << x << "; " << y << ") НЕ належить помаранчевій області.\n";
}

