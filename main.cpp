// Завдання 3. Головна функція: меню вибору завдання (switch)
// ---------------------------------------------------------------
int main() {
#ifdef _WIN32
    SetConsoleOutputCP(CP_UTF8);   // кирилиця у виводі
    SetConsoleCP(CP_UTF8);         // кирилиця у вводі
#endif

    int choice = -1;               // початкове значення, щоб цикл гарантовано розпочався
    do {
        cout << "\n========== МЕНЮ ==========\n"
             << "1 - Завдання If16\n"
             << "2 - Завдання If12\n"
             << "3 - Фігура 32\n"
             << "0 - Вихід\n"
             << "Ваш вибір: ";

        if (!readInt(choice)) {                       // перевірка введення пункту меню
            if (cin.eof()) {                          // введення закінчилось
                cout << "\nКінець введення. Завершення програми.\n";
                break;
            }
            cout << "Помилка: введіть ціле число від 0 до 3!\n";
            clearLine();
            choice = -1;                              // залишаємось у меню
            continue;
        }
        clearLine();

        switch (choice) {                             // вибір завдання
            case 1: taskIf16();     break;
            case 2: taskIf12();     break;
            case 3: taskFigure32(); break;
            case 0: cout << "Завершення програми.\n"; break;
            default: cout << "Невірний пункт меню! Допустимі значення: 0, 1, 2, 3.\n";
        }
    } while (choice != 0);

    return 0;
}
